function changeLanguage(language) {
    localStorage.setItem("selectedLanguage", language);
    applyLanguage(language);
}

function applyLanguage(language) {
    const selected = translations[language] || translations.English;

    document.querySelectorAll("[data-lang]").forEach(function(element) {
        const key = element.getAttribute("data-lang");

        if (selected[key]) {
            element.innerText = selected[key];
        }
    });
}
function addLanguageSelector() {
    const selector = document.createElement("select");

    selector.id = "languageSelector";

    selector.innerHTML = `
        <option value="English">🇬🇧 English</option>
        <option value="Tamil">🇮🇳 தமிழ்</option>
        <option value="Hindi">🇮🇳 हिन्दी</option>
        <option value="Thanglish">🗣️ Thanglish</option>
        <option value="Kannada">🇮🇳 ಕನ್ನಡ</option>
        <option value="Malayalam">🇮🇳 മലയാളം</option>
    `;

    selector.value = localStorage.getItem("selectedLanguage") || "English";

    selector.onchange = function() {
        changeLanguage(this.value);
    };

    document.body.prepend(selector);
}
document.addEventListener("DOMContentLoaded", function() {
    addLanguageSelector();

    const savedLanguage =
        localStorage.getItem("selectedLanguage") || "English";

    applyLanguage(savedLanguage);
});
